def versions_html() -> str:
    parts = [f"<h2>13. 버전별 바뀐 점</h2><p>지금 쓰는 버전: <b>v{config.APP_VERSION}</b></p>"]
    for version, items in VERSION_NOTES:
        lis = "".join(f"<li>{item}</li>" for item in items)
        parts.append(f"<h3>v{version}</h3><ul>{lis}</ul>")
    return "".join(parts)


def section_html(key: str) -> str:
    if key == "versions":
        return versions_html()
    for k, _title, html in SECTIONS:
        if k == key:
            return html
    return ""
