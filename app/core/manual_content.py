SECTION_KEYS = [k for k, _, _ in SECTIONS]


def plain_text(html: str) -> str:
    """검색용 — 태그를 뗀 글자만."""
    import re
    return re.sub(r"<[^>]+>", " ", html)


def search(query: str) -> list:
    """검색어가 제목이나 본문에 들어 있는 장의 키 목록(목차 순서)."""
    q = (query or "").strip()
    if not q:
        return list(SECTION_KEYS)
    return [k for k, title, html in SECTIONS if q in title or q in plain_text(html)]
